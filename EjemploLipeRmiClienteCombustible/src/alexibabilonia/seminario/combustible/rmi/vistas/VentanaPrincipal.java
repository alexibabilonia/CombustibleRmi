    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        try {
    if (calculoRemoto == null) {
        JOptionPane.showMessageDialog(
                this,
                "Primero debes conectarte al servidor."
        );
        return;
    }

    float kilometros = Float.parseFloat(
            txtKilometros.getText().trim().replace(',', '.')
    );

    float litros = Float.parseFloat(
            txtLitros.getText().trim().replace(',', '.')
    );

    if (kilometros <= 0 || litros <= 0) {
        JOptionPane.showMessageDialog(
                this,
                "Los kilometros y los litros deben ser mayores que cero."
        );
        return;
    }

    DatosCombustible datos = new DatosCombustible(
            kilometros,
            litros
    );

    DatosCombustible respuesta =
            calculoRemoto.calcularRendimiento(datos);

    hola.setText(
            String.format(
                    java.util.Locale.US,
                    "%.2f km/L",
                    respuesta.getResultado()
            )
    );

} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(
            this,
            "Ingrese valores numericos validos."
    );

} catch (Exception ex) {
    JOptionPane.showMessageDialog(
            this,
            "Error al calcular el rendimiento: " + ex.getMessage()
    );
}
    }//GEN-LAST:event_btnCalcularActionPerformed

