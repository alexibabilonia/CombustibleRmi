    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
   try {
    if (cliente == null) {
        int puerto = Integer.parseInt(txtPuerto.getText().trim());
        String ipServidor = txtIP.getText().trim();

        invocadorRemoto = new CallHandler();

        cliente = new Client(ipServidor, puerto, invocadorRemoto);

        calculoRemoto = (IRemotaCalculoCombustible)
                cliente.getGlobal(IRemotaCalculoCombustible.class);

        btnIniciar.setText("Desconectar");
        lblEstado.setText("Conectado");
        btnCalcular.setEnabled(true);

        JOptionPane.showMessageDialog(this, "Conexión exitosa");

    } else {
        cliente.close();

        cliente = null;
        calculoRemoto = null;
        invocadorRemoto = null;

        btnIniciar.setText("Iniciar");
        lblEstado.setText("Desconectado");
        btnCalcular.setEnabled(false);
    }

} catch (Exception ex) {
    ex.printStackTrace();

    JOptionPane.showMessageDialog(
            this,
            "Error al conectar: " + ex.getMessage()
    );
}
    }//GEN-LAST:event_btnIniciarActionPerformed

